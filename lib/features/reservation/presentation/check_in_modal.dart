  @override
  void initState() {
    super.initState();
    _priceController = TextEditingController(
      text: (widget.room.basePricePerNight * _totalNights).toInt().toString(),
    );
    if (_bookingSource == 'REDDOORZ') {
      _paymentMethod = 'REDDOORZ_PREPAID';
    }
  }

  @override
  void dispose() {
    _bookingCodeController.dispose();
    _nikController.dispose();
    _nameController.dispose();
    _addressController.dispose();
    _phoneController.dispose();
    _priceController.dispose();
    super.dispose();
  }

  void _setNights(int nights) {
    if (nights < 1) return;
    setState(() {
      _totalNights = nights;
      if (!_isManualPrice) {
        _priceController.text = (widget.room.basePricePerNight * _totalNights).toInt().toString();
      }
    });
  }

  void _resetPriceToStandard() {
    setState(() {
      _isManualPrice = false;
      _priceController.text = (widget.room.basePricePerNight * _totalNights).toInt().toString();
    });
  }

  double get _currentEffectiveTotal {
    final parsed = double.tryParse(_priceController.text.replaceAll(RegExp(r'[^0-9]'), ''));
    if (parsed != null && parsed > 0) {
      return parsed;
    }
    return widget.room.basePricePerNight * _totalNights;
  }

  // Simulate Google Cloud Vision OCR Extraction
  Future<void> _simulateOcrScan() async {
    setState(() {
      _isOcrLoading = true;
      _errorMessage = null;
    });

    // Simulate 1.2s OCR processing (under 3s NFR limit)
    await Future.delayed(const Duration(milliseconds: 1200));

    // Sample data generated by OCR
    final sampleGuests = [
      {
        'nik': '3578012409890002',
        'name': 'BAMBANG PRASETYO',
        'address': 'JL. DIPONEGORO NO. 45, SURABAYA',
        'phone': '081298765432',
        'confidence': 0.94,
      },
      {
        'nik': '3171051508920004',
        'name': 'DEWI KARTIKA SARI',
        'address': 'JL. GATOT SUBROTO KAV. 18, JAKARTA',
        'phone': '085612349876',
        'confidence': 0.91,
      },
      {
        'nik': '3273024806870001',
        'name': 'AHMAD FAUZI',
        'address': 'JL. ASIA AFRIKA NO. 110, BANDUNG',
        'phone': '087812908765',
        'confidence': 0.96,
      },
    ];

    final picked = sampleGuests[DateTime.now().second % sampleGuests.length];

    setState(() {
      _isOcrLoading = false;
      _isOcrExtracted = true;
      _nikController.text = picked['nik'] as String;
      _nameController.text = picked['name'] as String;
      _addressController.text = picked['address'] as String;
      if (_phoneController.text.isEmpty) {
        _phoneController.text = picked['phone'] as String;
      }
      _ocrConfidence = picked['confidence'] as double;
    });
  }

  void _handleSubmit() async {
    if (!_formKey.currentState!.validate()) return;

    // Validate anti-duplicate NIK in active rooms (FR-RES-07)
    final allRooms = ref.read(roomListProvider).value ?? [];
    final cleanNik = _nikController.text.trim();
    final duplicate = allRooms.any((r) =>
        r.isOccupied &&
        r.id != widget.room.id &&
        (r.guestNik != null && r.guestNik == cleanNik));

    if (duplicate) {
      setState(() {
        _errorMessage = 'Tamu dengan NIK $cleanNik sedang aktif menginap di kamar lain!';
      });
      return;
    }

    final effectiveTotal = _currentEffectiveTotal;
    final calculatedBasePrice = effectiveTotal / _totalNights;

    try {
      await ref.read(roomListProvider.notifier).checkIn(
            roomId: widget.room.id,
            guestName: _nameController.text.trim(),
            guestNik: cleanNik,
            guestPhone: _phoneController.text.trim(),
            bookingSource: _bookingSource,
            reddoorzBookingCode: _bookingSource == 'REDDOORZ'
                ? _bookingCodeController.text.trim()
                : null,
            totalNights: _totalNights,
            basePrice: calculatedBasePrice,
            paymentMethod: _paymentMethod,
          );

      if (mounted) {
        Navigator.of(context).pop();
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            backgroundColor: AppColors.statusAvailable,
            content: Row(
              children: [
                const Icon(Icons.check_circle_outline, color: Colors.white),
                const SizedBox(width: 8),
                Text(
                  'Check-in Kamar ${widget.room.roomNumber} berhasil! Notifikasi WA pengingat check-out telah dijadwalkan.',
                  style: const TextStyle(color: Colors.white),
                ),
              ],
            ),
          ),
        );
      }
    } catch (e) {
      setState(() {
        _errorMessage = e.toString().replaceAll('Exception: ', '');
      });
    }
  }

